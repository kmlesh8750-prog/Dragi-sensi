export function buildCustomDevice(
  customName: string,
  opts: {
    os: DeviceOS;
    ramGB: number;
    refreshRate: number;
  }
): DeviceProfile {
  const cleanName = customName.trim() || 'Custom Gaming Phone';
  const tier: ChipsetTier =
    opts.os === 'ios'
      ? 'ios'
      : opts.ramGB >= 12 || opts.refreshRate >= 144
      ? 'flagship'
      : opts.ramGB >= 8 && opts.refreshRate >= 120
      ? 'upper'
      : opts.ramGB >= 6
      ? 'mid'
      : 'entry';

  const touchSamplingHz =
    opts.os === 'ios'
      ? opts.refreshRate >= 120
        ? 240
        : 120
      : opts.refreshRate >= 144
      ? 360
      : opts.refreshRate >= 120
      ? 240
      : opts.refreshRate >= 90
      ? 180
      : 120;

  const defaultDpi = opts.os === 'ios' ? 393 : opts.ramGB >= 8 ? 411 : 360;
  const maxSafeDpi =
    opts.os === 'ios'
      ? 500
      : tier === 'flagship'
      ? 780
      : tier === 'upper'
      ? 700
      : tier === 'mid'
      ? 620
      : 500;

  return {
    id: 'custom-device',
    name: cleanName,
    brand: opts.os === 'ios' ? 'Apple' : 'Custom',
    os: opts.os,
    refreshRate: opts.refreshRate,
    touchSamplingHz,
    ramGB: opts.ramGB,
    screenInches: 6.67,
    defaultDpi,
    maxSafeDpi,
    chipsetTier: tier,
    isCustom: true,
  };
}
